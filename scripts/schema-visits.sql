-- Idempotent migration: ziyaretçi / unique-kişi sayımı altyapısı
-- Kullanıcı Supabase SQL Editor'de çalıştıracak (exec_sql / SUPABASE_DB_PY yok).

-- Ziyaretçi oturumu kimliği (first-party cookie ile eşleşir)
CREATE TABLE IF NOT EXISTS visits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id text NOT NULL,
  user_id text NULL,                       -- girişliyse kullanıcı kimliği
  path text NOT NULL,
  day date NOT NULL,                       -- YYYY-MM-DD, kişi+gün başına tek satır
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS visits_visitor_day_unique
  ON visits (visitor_id, day);

CREATE INDEX IF NOT EXISTS visits_day_idx ON visits (day);
CREATE INDEX IF NOT EXISTS visits_visitor_idx ON visits (visitor_id);
CREATE INDEX IF NOT EXISTS visits_user_idx ON visits (user_id) WHERE user_id IS NOT NULL;

-- visitorId <-> userId eşleşmesi (giriş yapınca geri dönük bağlar)
CREATE TABLE IF NOT EXISTS visitor_links (
  visitor_id text NOT NULL,
  user_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (visitor_id, user_id)
);
CREATE INDEX IF NOT EXISTS visitor_links_user_idx ON visitor_links (user_id);

-- Uygulama ayarları (anahtar/değer, tek satır)
CREATE TABLE IF NOT EXISTS app_settings (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Okuma kolaylığı: günlük unique kişi sayımı (view)
CREATE OR REPLACE VIEW visit_stats AS
SELECT
  day,
  COUNT(DISTINCT visitor_id) AS gunluk_kisi,
  COUNT(*) AS gunluk_ziyaret
FROM visits
GROUP BY day;

COMMENT ON TABLE visits IS 'Günlük unique ziyaretçi kaydı (IP saklanmaz, visitorId cookie üzerinden).';
COMMENT ON COLUMN visits.visitor_id IS 'First-party visitorId cookie değeri (1 yıl, httpOnly).';
COMMENT ON COLUMN visits.user_id IS 'Girişliyse Supabase auth userId; yoksa NULL.';
COMMENT ON COLUMN visits.day IS 'UTC tarih (YYYY-MM-DD); unique(visitor_id, day) kısıtlaması ile kişi+gün tek satır.';
